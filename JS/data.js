/* ================= VERIFICATION STATE ================= */

function normalizeVerificationStatus(property) {
    const rawStatus = String(property?.verificationStatus || "")
        .trim()
        .toLowerCase();

    // Rejection always wins over a stale verified flag.
    if (rawStatus === "rejected") {
        return "rejected";
    }

    if (
        rawStatus === "pending" ||
        rawStatus === "pending verification"
    ) {
        return "pending";
    }

    if (
        rawStatus === "approved" ||
        rawStatus === "verified" ||
        property?.verified === true
    ) {
        return "approved";
    }

    return "pending";
}

function isPropertyVerified(property) {
    return normalizeVerificationStatus(property) === "approved";
}

function isPropertyRejected(property) {
    return normalizeVerificationStatus(property) === "rejected";
}

/** Normalized marketplace listing lifecycle */
function getListingStatus(property) {
    if (!property) return "pending";
    if (isPropertyRejected(property)) return "rejected";

    const ls = String(property.listingStatus || "")
        .trim()
        .toLowerCase();

    if (ls === "draft" || ls === "paused" || ls === "live" || ls === "pending") {
        return ls;
    }

    // Legacy demo data: verified flag / approved status counts as live
    if (isPropertyVerified(property)) return "live";
    return "pending";
}

function countPropertyPhotos(property) {
    if (Array.isArray(property?.images) && property.images.length) {
        return property.images.filter(Boolean).length;
    }
    return property?.image ? 1 : 0;
}

const LEASEACCOM_MIN_PUBLIC_PHOTOS = 4;
const LEASEACCOM_MIN_DESCRIPTION = 40;

/**
 * Public marketplace rules:
 * - not rejected
 * - listingStatus live (or legacy verified)
 * - enough photos
 * - has title, price, location
 */
function isPropertyPublic(property) {
    if (!property || isPropertyRejected(property)) return false;
    if (getListingStatus(property) !== "live") return false;

    const photos = countPropertyPhotos(property);
    if (photos < LEASEACCOM_MIN_PUBLIC_PHOTOS) return false;

    const title = String(property.title || "").trim();
    const location = String(property.location || property.city || "").trim();
    const price = Number(property.price) || 0;
    if (!title || !location || price <= 0) return false;

    return true;
}

function getListingQualityReport(property) {
    const photos = countPropertyPhotos(property);
    const desc = String(property.description || "").trim();
    const checks = [
        { ok: photos >= LEASEACCOM_MIN_PUBLIC_PHOTOS, label: `At least ${LEASEACCOM_MIN_PUBLIC_PHOTOS} photos`, detail: photos + " uploaded" },
        { ok: desc.length >= LEASEACCOM_MIN_DESCRIPTION, label: "Clear description", detail: desc.length + " characters" },
        { ok: (Number(property.price) || 0) > 0, label: "Rent price set", detail: "" },
        { ok: Boolean(String(property.location || property.city || "").trim()), label: "Location set", detail: "" },
        { ok: Boolean(String(property.title || "").trim()), label: "Title set", detail: "" },
        { ok: Boolean(property.type), label: "Property type set", detail: "" }
    ];
    const passed = checks.filter(c => c.ok).length;
    return { checks, passed, total: checks.length, ready: passed === checks.length };
}

/* ================= LOCAL PROPERTIES ================= */

let savedLeaseAccomProperties = [];

try {
    const savedProperties = JSON.parse(
        localStorage.getItem("leaseaccomProperties") || "[]"
    );

    savedLeaseAccomProperties = Array.isArray(savedProperties)
        ? savedProperties
        : [];
} catch (error) {
    console.warn("LeaseAccom property data could not be read.", error);
}

savedLeaseAccomProperties.forEach(savedProperty => {
    const existingIndex = properties.findIndex(property =>
        String(property.id) === String(savedProperty.id)
    );

    if (existingIndex === -1) {
        properties.push(savedProperty);
    } else {
        // Local data contains the latest verification and owner changes.
        properties[existingIndex] = {
            ...properties[existingIndex],
            ...savedProperty
        };
    }
});

/* ================= SORT BY VERIFICATION ================= */

const verificationOrder = {
    approved: 0,
    pending: 1,
    rejected: 2
};

properties.sort((a, b) => {
    return (
        verificationOrder[normalizeVerificationStatus(a)] -
        verificationOrder[normalizeVerificationStatus(b)]
    );
});


